"""Build data for the Auditor Assist demo page (demo/index.html).

  --synthetic                 the fictional interview -> demo/demo-data.js (committed)
  --sample-dir <dir>          a real audited interview -> data/private/demo/<id>.json
                              (open it in the page with "Open interview"; stays local)

Both run the real audit runner, so the page shows what the engine decides.
"""

import argparse
import json
import wave
from pathlib import Path

import numpy as np

from src.audit_policy.parser import parse_audit_project
from src.demo import synthetic
from src.demo.view_model import build_view_model, synthetic_waveform
from src.full_sample.audit_runner import evaluate_full_sample

DEMO_DIR = Path("demo")


def load(path: Path):
    return json.loads(path.read_text(encoding="utf-8-sig"))


def build_synthetic() -> dict:
    inputs = synthetic.build_inputs()
    report = evaluate_full_sample(
        dialogues=inputs["dialogues"], windows=inputs["windows"],
        survey_definition=inputs["survey_definition"], policy=inputs["policy"],
        human_audit=inputs["human_audit"],
    )
    return build_view_model(
        report=report, dialogues=inputs["dialogues"], windows=inputs["windows"],
        survey_definition=inputs["survey_definition"], policy=inputs["policy"],
        interview_turns=inputs["interview_turns"],
        waveform=synthetic_waveform(inputs["interview_turns"], synthetic.DURATION_SEC),
        duration_sec=synthetic.DURATION_SEC, interview_id=synthetic.INTERVIEW_ID, synthetic=True,
    )


def real_waveform(audio: Path, bins: int = 720) -> tuple[list[float], float]:
    with wave.open(str(audio)) as handle:
        rate = handle.getframerate()
        samples = np.frombuffer(handle.readframes(handle.getnframes()), dtype=np.int16).astype(np.float64)
    duration = len(samples) / rate
    edges = np.linspace(0, len(samples), bins + 1).astype(int)
    rms = np.array([np.sqrt(np.mean(samples[a:b] ** 2)) if b > a else 0.0 for a, b in zip(edges, edges[1:])])
    peak = float(np.percentile(rms, 99)) or 1.0
    return [round(float(min(1.0, v / peak)), 3) for v in rms], duration


def build_real(sample_dir: Path) -> dict:
    snapshot = load(sample_dir / "audit_policy_snapshot.json")
    policy = parse_audit_project({"project_code": snapshot[0]["project_code"], "project_tags": snapshot}, active_only=False)
    dialogues = load(sample_dir / "prompting_dialogue_clean.json")
    windows = load(sample_dir / "question_asr.json")
    definition = load(sample_dir / "survey_definition.json")
    report = evaluate_full_sample(
        dialogues=dialogues, windows=windows, survey_definition=definition,
        policy=policy, human_audit=load(sample_dir / "human_audit.json"),
    )
    transcripts = {r["audio_file"]: r["transcript"] for r in load(sample_dir / "prompting_turn_asr_results_clean.json")}
    turns_path = sample_dir / "interview_turns.json"
    interview_turns = []
    if turns_path.exists():
        for turn in load(turns_path):
            interview_turns.append({**turn, "transcript": transcripts.get(turn.get("clip_name") or "", "")})
    waveform, duration = real_waveform(sample_dir / "interview_16k_mono.wav")
    return build_view_model(
        report=report, dialogues=dialogues, windows=windows, survey_definition=definition, policy=policy,
        interview_turns=interview_turns, waveform=waveform, duration_sec=duration,
        interview_id=sample_dir.name[:8], synthetic=False,
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--synthetic", action="store_true")
    group.add_argument("--sample-dir", type=Path)
    args = parser.parse_args()

    if args.synthetic:
        model = build_synthetic()
        out = DEMO_DIR / "demo-data.js"
        out.write_text(
            "// Generated by `python -m scripts.build_demo --synthetic`. Fictional interview; do not edit.\n"
            "window.DEMO_DATA = " + json.dumps(model, ensure_ascii=False, separators=(",", ":")) + ";\n",
            encoding="utf-8",
        )
    else:
        model = build_real(args.sample_dir)
        out = Path("data/private/demo") / f"{args.sample_dir.name}.json"
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(json.dumps(model, ensure_ascii=False), encoding="utf-8")

    s = model["summary"]
    print(f"{model['interview']['id']}: {s['questions']} questions, auto {s['auto']}, prefill {s['prefill']}, review {s['review']}")
    print(f"Saved: {out}")


if __name__ == "__main__":
    main()
